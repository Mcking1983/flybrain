def it(t):
    pdf.set_font("cjk", "I", 9.5); pdf.multi_cell(0, 5.2, t); pdf.ln(1)

def figimg(path, cap):
    pdf.image(path, x=22, w=170); pdf.ln(2)
    it(cap); pdf.ln(1)

def table(caption, rows, widths):
    it(caption); pdf.ln(0.5)
    pdf.set_font("cjk", "B", 8.8)
