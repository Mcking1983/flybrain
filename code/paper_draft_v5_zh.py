h2("8. 讨论")
p("基底帮上忙的地方只有一处，而且是实打实的一处：对比度读数下廉价的逐任务门信号，维持每种群每代 40-55/144 次零 token 执行、"
  "单蝇 8/18，基因组为保住这个信号而进化（放宽边界第 4 代破壳，原始边界盒第 217 代）。这就是模型级联里路由器的生物学版本——"
  "而我们的测量说明路由信号必须是对比度的：全运动区速率是打满的表针，不是决策。")
p("决策层假设为什么死，机制上很清楚：1-2 步的状态保持加近线性输入中继，除了线索本来就带着的东西之外，留不下任何任务身份的基底；"
  "分类器结果（原始输入 1.000 对 chance 0.056）说明任务标签在线索里，不在网络对它的变换里。习得对先天的余弦对（0.9723 对 0.0618）"
  "把贡献定位在可塑性上，不在先天图上。")
p("对照臂的读法（表 6）：无脑连吃都学不会——可塑性自己起不了步；重连脑全活、餐食最高，但见啥吃啥、吃饱还吃——门对结构是敏感的，"
  "对权重随机化不宽容；掷币脑半学会门但能量为负——随机决策要付能量。真脑能量低于重连脑：门用少吃的餐食买「吃饱就停」。"
  "一句话：结构买的是门，不是热量。")
p("局限。经济谱系结果立于两条独立谱系加一条 20 代平台（三个谱系、一个迁移种子）；对照臂现在有两种子（11、12），"
  "rewired 能量反超真脑在两个种子上都成立——但两种子之间的差同时换了设备（11 在本机 CPU、12 在云 GPU 的 CUDA 路径），"
  "种子效应与设备效应没有拆开。教师迁移的 token 数按工件层面引用（操作数与回复长度已重导；token 数依赖分词器）。"
  "solo 数依赖技能库覆盖度；5,987 突触与 738,868 突触的两只蝇都拿 8/18，突触数不是驱动力。CUDA 与 MPS 数值路径在迁移边界差约 +0.06 rate_sum，"
  "跨机复现必须钉死设备。ok 指标饱和，不用于任何主张。")

